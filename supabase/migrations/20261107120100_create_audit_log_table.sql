-- Supabase Migration: Crear la tabla de bitácora de auditoría `audit_log`
--
-- Issue #66 — El endpoint de búsqueda del médico es el primer acceso de ese rol a datos de
-- salud de estudiantes de varias escuelas, y la skill `audit-logging` exige registrar los
-- accesos a datos médicos/PHR. Hasta ahora no existía tabla de auditoría en el proyecto:
-- `app/services/admin_service.py:86` dejaba el TODO desde la fase de administración global.
--
-- Diseño:
--   * Append-only: no hay camino de UPDATE ni DELETE en el código, y el `service_role` es el
--     único que escribe. Las correcciones se hacen añadiendo filas, nunca editando.
--   * `school_id` es NULL solo en acciones globales de `admin_sistema`. Para el resto se
--     resuelve en el servidor (ver `.agents/rules/tenant-isolation.md`).
--   * `metadata` guarda filtros aplicados y número de resultados. `changes` guarda nombres de
--     campo y banderas, NUNCA valores clínicos: la minimización de PHR/PII es parte del
--     contrato de la skill `audit-logging`.
--   * No hay FK hacia `public."user"`: la bitácora debe sobrevivir al borrado del actor.
--
-- RLS: se habilita **sin políticas**, igual que `settings`. Con RLS activo y cero políticas la
-- `anon key` —la que usa el backend y la que viaja al frontend— no puede leer ni escribir la
-- bitácora por la Data API. El único camino de escritura es el cliente `service_role`
-- (`supabase_admin` en `app/core/database.py`), cuya clave nunca sale del servidor.

CREATE TABLE IF NOT EXISTS public.audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    bigint      NOT NULL,
    actor_role  text        NOT NULL,
    school_id   bigint      REFERENCES public.school (sch_id),
    action      text        NOT NULL,
    entity      text        NOT NULL,
    entity_id   text,
    changes     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    metadata    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT audit_log_action_valid CHECK (
        action IN ('read', 'create', 'update', 'delete', 'approve', 'reject', 'export')
    ),
    CONSTRAINT audit_log_changes_is_object  CHECK (jsonb_typeof(changes) = 'object'),
    CONSTRAINT audit_log_metadata_is_object CHECK (jsonb_typeof(metadata) = 'object')
);

-- Consultas previstas: "qué hizo este actor" y "qué pasó en esta escuela", ambas recientes primero.
CREATE INDEX IF NOT EXISTS idx_audit_log_actor_created
    ON public.audit_log (actor_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_log_school_created
    ON public.audit_log (school_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_log_entity
    ON public.audit_log (entity, entity_id);

-- Sin políticas: deniega todo a `anon` y `authenticated`. `service_role` la omite por diseño.
-- Idempotente: habilitar RLS ya habilitado no falla.
ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.audit_log IS
    'Bitácora append-only de acciones sensibles: accesos y cambios sobre datos médicos/PHR, '
    'aprobaciones de usuarios, acciones globales de admin_sistema y exportaciones.';
COMMENT ON COLUMN public.audit_log.school_id IS
    'Escuela en cuyo ámbito ocurrió la acción. NULL solo en acciones globales de admin_sistema.';
COMMENT ON COLUMN public.audit_log.changes IS
    'Nombres de campo y banderas de cambio. Nunca valores clínicos, credenciales ni documentos de identidad.';
COMMENT ON COLUMN public.audit_log.metadata IS
    'Contexto no sensible de la acción: filtros aplicados, número de resultados, motivo.';
