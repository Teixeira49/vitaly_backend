-- Supabase Migration: Crear la tabla de configuración global `settings`
--
-- Issue #44 — Validar anticipación configurable al crear revisiones escolares.
--
-- Diseño:
--   * Alcance GLOBAL del sistema: una fila por clave de configuración, sin
--     `school_id`. Si en el futuro se requiere configuración por institución,
--     se añadirá una columna `school_id` nullable (NULL = valor global) y un
--     índice único sobre (key, COALESCE(school_id, -1)).
--   * `key` identifica el tipo de configuración (ver `SettingKey` en
--     `app/schemas/enums.py`).
--   * `value` es un objeto JSON autodescriptivo `{"type": ..., "value": ...}`
--     para que una misma tabla soporte cualquier tipo de dato sin migraciones
--     adicionales. Los CHECK garantizan que el tipo declarado coincida con el
--     tipo JSON real almacenado.
--   * La ausencia de fila, el borrado lógico (`is_deleted`) o un valor fuera de
--     rango NO desactivan ninguna barrera de negocio: el servicio cae al valor
--     por defecto definido en código (ver `app/services/settings_service.py`).
--
-- Escritura: solo el rol `admin_sistema` a través de `/api/v1/admin/settings`.
-- RLS: no se habilita, en línea con el resto de tablas del proyecto (el backend
-- es el único cliente y usa la service key).

CREATE TABLE IF NOT EXISTS public.settings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         text        NOT NULL,
    value       jsonb       NOT NULL,
    description text,
    is_deleted  boolean     NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT settings_key_unique UNIQUE (key),

    -- El valor siempre es un objeto con tipo declarado y dato.
    CONSTRAINT settings_value_shape CHECK (
        jsonb_typeof(value) = 'object'
        AND value ? 'type'
        AND value ? 'value'
        AND value ->> 'type' IN ('integer', 'number', 'string', 'boolean', 'json')
    ),

    -- El tipo declarado coincide con el tipo JSON real del dato almacenado.
    CONSTRAINT settings_value_type_match CHECK (
        (value ->> 'type' = 'integer' AND jsonb_typeof(value -> 'value') = 'number')
        OR (value ->> 'type' = 'number'  AND jsonb_typeof(value -> 'value') = 'number')
        OR (value ->> 'type' = 'string'  AND jsonb_typeof(value -> 'value') = 'string')
        OR (value ->> 'type' = 'boolean' AND jsonb_typeof(value -> 'value') = 'boolean')
        OR (value ->> 'type' = 'json'    AND jsonb_typeof(value -> 'value') IN ('object', 'array'))
    )
);

COMMENT ON TABLE public.settings IS
    'Configuración global del sistema. Una fila por clave; el valor es un objeto JSON autodescriptivo {"type": ..., "value": ...}.';
COMMENT ON COLUMN public.settings.key IS
    'Tipo de configuración. Debe coincidir con un miembro de SettingKey (app/schemas/enums.py).';
COMMENT ON COLUMN public.settings.value IS
    'Objeto JSON {"type": "integer|number|string|boolean|json", "value": <dato>}.';

